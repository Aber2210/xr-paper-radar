def idx(prefix, start=0):
    hits = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    assert len(hits) == 1, (prefix, len(hits))
    return hits[0]


def row(x):
    return '| {r} | {t} | {tr} | {v:.2f} | {g} | {e} |'.format(
        r=x['_rank'], t=x['title_zh'], tr=x['track'], v=x['value'],
        g=x['grade'], e=x['evidence'].split('/')[0])


def top10(batch):
    d = [x for x in json.load(open('data/scored_' + batch + '.json', encoding='utf-8'))
         if x.get('in_top10')]
    d.sort(key=lambda x: -x['value'])
    for i, x in enumerate(d, 1):
        x['_rank'] = i
    return d


